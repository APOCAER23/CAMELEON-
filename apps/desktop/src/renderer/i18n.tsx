export const translations: Record<SupportedLanguage, Record<string, string>> = {
  en,
  fr,
  es,
  de: { ...en, ...de },
  it: { ...en, ...it },
  pt: { ...en, ...pt },
  nl: { ...en, ...nl },
  ru: { ...en, ...ru },
  zh: { ...en, ...zh },
  ja: { ...en, ...ja },
  ko: { ...en, ...ko },
  ar: { ...en, ...ar },
};

interface I18nContextValue {
  language: SupportedLanguage;
  setLanguage: (lang: SupportedLanguage) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue>({
  language: 'en',
  setLanguage: () => undefined,
  t: (k) => k,
});

const STORAGE_KEY = 'cameleon_language';

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLangState] = useState<SupportedLanguage>(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY) as SupportedLanguage | null;
      if (saved && LANGUAGES.some((l) => l.code === saved)) return saved;
    } catch {
      /* ignore */
    }
    return 'en';
  });

  useEffect(() => {
    if (window.cameleon?.settings) {
      window.cameleon.settings
        .get()
        .then((s) => {
          if (s?.language && LANGUAGES.some((l) => l.code === s.language)) {
            setLangState(s.language);
            try {
              localStorage.setItem(STORAGE_KEY, s.language);
            } catch {
              /* ignore */
            }
          }
        })
        .catch(() => undefined);
    }
  }, []);

  const setLanguage = (lang: SupportedLanguage) => {
    setLangState(lang);
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      /* ignore */
    }
    if (window.cameleon?.settings) {
      void window.cameleon.settings.set({ language: lang });
    }
  };

  const t = (key: string, vars?: Record<string, string | number>): string => {
    const langDict = translations[language];
    let text = (langDict && key in langDict ? langDict[key] : undefined) ?? translations.en[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        text = text.replaceAll(`{${k}}`, String(v));
      }
    }
    return text;
  };

  return <I18nContext.Provider value={{ language, setLanguage, t }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
